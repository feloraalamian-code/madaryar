const lastAnswers: Record<string, string> = {};

export function findAnswer(question: string): string {
  const normalized = question.toLowerCase();

  for (const [topicKey, topic] of Object.entries(topics)) {
    for (const keyword of topic.keywords) {
      if (normalized.includes(keyword)) {
        let availableAnswers = topic.answers;
        const last = lastAnswers[topicKey];
        if (topic.answers.length > 1 && last) {
          availableAnswers = topic.answers.filter((a) => a !== last);
        }
        const answer =
          availableAnswers[Math.floor(Math.random() * availableAnswers.length)];
        lastAnswers[topicKey] = answer;
        return answer;
      }
    }
  }

  return fallbackAnswers[Math.floor(Math.random() * fallbackAnswers.length)];
}